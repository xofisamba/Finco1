# ── A. No raw navigation ─────────────────────────────────────────────────

class TestCompareShortcutNeverLeavesSPA:
    def test_compare_link_macro_uses_htmx_not_plain_navigation(self):
        tpl = (REPO_ROOT / "app/templates/partials/scenario_workflow_indicators.html").read_text()
        # The compare_link macro must carry hx-get / hx-target / hx-swap.
