# ── File-scope guardrail ──────────────────────────────────────────────────

class TestUX2GFileScope:
    """UX-2G-COMPARE-FIX must never touch engine/domain/runtime/export/
    validation code. UI/template/test files only."""

    ALLOWED_PREFIXES = (
        "main_web.py",
        "app/ui/scenario_workflow.py",
        "app/templates/partials/scenario_workflow_indicators.html",
        "app/templates/partials/workspace_shell.html",
        "tests/test_ux2g_compare_fix.py",
        # UX-2I-PILOT-POLISH-FOLLOWUP: reliable Compare tab activation
        # (static/app.js) + stale no-run banner cleanup
        # (shared_runtime_block.html) + sessionStorage serialization fix
        # (run_service.py). Presentation/routing only.
        "static/app.js",
        "app/templates/partials/shared_runtime_block.html",
        "app/services/run_service.py",
        "tests/test_ux2i_pilot_polish_followup.py",
    )
    DISALLOWED_PREFIXES = (
        "domain/",
        "app/waterfall_core.py",
        "app/input_adapter.py",
        "app/project_factories.py",
    )

    def test_changed_files_within_allowlist(self):
        import subprocess
        try:
            out = subprocess.run(
                ["git", "diff", "--name-only", "origin/main"],
                cwd=str(REPO_ROOT), capture_output=True, text=True, timeout=30,
            )
        except Exception:
            pytest.skip("git not available in this environment")
        if out.returncode != 0 or not out.stdout.strip():
            pytest.skip("no diff against origin/main available")
        changed = [l.strip() for l in out.stdout.splitlines() if l.strip()]
        for f in changed:
            assert not any(f.startswith(p) for p in self.DISALLOWED_PREFIXES), (
                f"UX-2G must not touch {f}"
            )
