# ── B. Comparison table actually renders ─────────────────────────────────

class TestComparePanelRendersTable:
    def test_compare_panel_endpoint_exists_and_returns_fragment(self, auth_client):
        resp = auth_client.get("/scenarios/compare-panel")
        assert resp.status_code == 200
        body = resp.text
        # Fragment only -- never a full standalone page.
        assert "<html" not in body.lower()
        assert "<head" not in body.lower()

    def test_compare_panel_renders_actual_table_when_scenarios_given(
        self, auth_client, two_projects_with_scenarios
    ):
        proj = two_projects_with_scenarios["ux2g-proj-a"]
        left, right = proj["scenario_ids"]
        resp = auth_client.get(
            "/scenarios/compare-panel",
            params={
                "project": "ux2g-proj-a",
                "left_scenario_id": left,
                "right_scenario_id": right,
            },
        )
        assert resp.status_code == 200
        body = resp.text
        # The real comparison table markup must be present, not just
        # a metadata-only notice.
        assert "ux2g-proj-a Base" in body or "ux2g-proj-a Downside" in body

    def test_workspace_shell_has_compare_mount_target(self):
        tpl = (REPO_ROOT / "app/templates/partials/workspace_shell.html").read_text()
        assert 'id="panel-compare-mount"' in tpl
        assert 'id="panel-compare"' in tpl


# ── C. Project scoping / wrong-project regression ────────────────────────

class TestCompareProjectScoping:
    def test_compare_panel_with_no_project_does_not_guess(self, auth_client):
        """Missing project must never silently default to any project
        (e.g. "tuho") -- this is the structural fix for root cause C."""
        resp = auth_client.get("/scenarios/compare-panel")
        assert resp.status_code == 200
        body = resp.text
        assert "tuho" not in body.lower()

    def test_compare_panel_rejects_cross_project_scenarios(
        self, auth_client, two_projects_with_scenarios
    ):
        """Scenarios from project A must not be comparable under project B."""
        proj_a = two_projects_with_scenarios["ux2g-proj-a"]
        left, right = proj_a["scenario_ids"]
        resp = auth_client.get(
            "/scenarios/compare-panel",
            params={
                "project": "ux2g-proj-b",
                "left_scenario_id": left,
                "right_scenario_id": right,
            },
        )
        assert resp.status_code == 200
        body = resp.text
        # Must not render project A's scenario names under project B.
        assert "ux2g-proj-a Base" not in body
        assert "ux2g-proj-a Downside" not in body

    def test_shortcut_href_always_carries_project_code(self):
        from app.ui.scenario_workflow import build_compare_shortcut_links

        cards = [
            {"scenario_id": "s1", "scenario_name": "Base", "equity_irr": 0.1},
            {"scenario_id": "s2", "scenario_name": "Downside", "equity_irr": 0.05},
        ]
        links = build_compare_shortcut_links(
            cards, active_scenario_id="s1", project_code="my-real-project",
        )
        assert links, "expected at least one compare shortcut link"
        for link in links:
            assert "project=my-real-project" in link["href"]

    def test_shortcut_href_without_project_code_has_no_project_param(self):
        """Documents legacy/no-project-passed behaviour: when no project
        code is available, no project param is added (the caller must
        supply one); this must not be re-interpreted as "use tuho"."""
        from app.ui.scenario_workflow import build_compare_shortcut_links

        cards = [
            {"scenario_id": "s1", "scenario_name": "Base", "equity_irr": 0.1},
            {"scenario_id": "s2", "scenario_name": "Downside", "equity_irr": 0.05},
        ]
        links = build_compare_shortcut_links(cards, active_scenario_id="s1")
        for link in links:
            assert "project=" not in link["href"]
            assert "tuho" not in link["href"]


