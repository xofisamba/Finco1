"""
UX-2G-COMPARE-FIX

UX-2F Final Visual QA flagged Compare as the only remaining P0 blocker
before the friendly pilot:
  A. "Compare with X" performed a raw <a href> navigation away from the SPA.
  B. The Compare tab rendered no comparison table (only metadata).
  C. Compare could resolve scenarios from the wrong project (e.g. "tuho"
     instead of the active project) because the shortcut href never
     carried a ``project=`` query param, so the legacy route's
     ``project: str = "tuho"`` default silently took over.

This file proves:
  1. The "Compare with X" link is htmx-only (hx-get/hx-target/hx-swap),
     never a navigation-only <a href> with no htmx attributes.
  2. /scenarios/compare-panel returns a fragment (no <head>, no <html>)
     containing the actual comparison table, not just metadata.
  3. /scenarios/compare-panel is always scoped to the project passed in,
     and silently produces an empty/no-compare fragment (never a guess)
     when project is missing.
  4. The shortcut href generated by build_compare_shortcut_links() always
     carries the active project's code.
  5. workspace_shell.html provides a stable #panel-compare-mount swap
     target for the Compare tab.
  6. No scenario/persistence/calculation regression: legacy
     /scenarios/compare route behaviour is unchanged.

No engine/domain/runtime/export/validation files are touched by this
test file or by the fix it verifies.
"""
