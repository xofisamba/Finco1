def test_no_magnitude_based_classification():
    """No row may have magnitude-based classification.

    Prohibited pattern: classification changes based on abs_delta threshold alone.
    Every non-MATCH row must have a root_cause that explains WHY (not just HOW BIG).
    """
    from finco_recon.recon_03_oborovo_full import build_delta_register, MATCH

    register = build_delta_register()
    for row in register:
        if row["classification"] != MATCH and row.get("absolute_delta") is not None:
            rc = row.get("root_cause", "").strip()
            assert rc, (
                f"Row {row.get('recon_id')!r} has classification "
                f"{row['classification']!r} but empty root_cause — "
                "classification must be cause-driven, not magnitude-based."
            )


def test_no_fabricated_zero_delta():
    """When excel_value or python_value is None, delta must be None (not 0.0).

    Req #2: Never compute delta against zero when a value is genuinely absent.
    """
    from finco_recon.recon_03_oborovo_full import build_delta_register

    register = build_delta_register()
    violations = []
    for row in register:
        ev = row["excel_value"]
        pv = row["python_value"]
        delta = row["delta"]
        if ev is None or pv is None:
            if delta is not None:
                violations.append(
                    f"  {row['recon_id']}: excel={ev}, python={pv}, delta={delta} "
                    "(should be None)"
                )
    assert not violations, (
        f"Found {len(violations)} rows with fabricated delta (None→0 substitution):\n"
        + "\n".join(violations[:10])
    )


