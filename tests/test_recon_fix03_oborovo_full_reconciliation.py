        f"Excel Average Senior DSCR = {excel_avg}. "
        f"Delta {abs(python_averageif - excel_avg):.4f} exceeds tolerance 0.10. "
        f"Valid period count: {len(valid)}. "
        "Check: are per-period DSCRs in financing.senior_debt.dscr correct?"
