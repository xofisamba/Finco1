@dataclass(frozen=True)
class ConstructionGeneratedVintage:
    """A tax loss carryforward generated during the construction period,
    supplied at the operation boundary.

    DISTINCT from OpeningTaxLossVintageInput (historical pre-construction losses).
    For TUHO: historical opening LCF = ZERO. This vintage represents losses
    generated during construction (SHL interest expensed through P&L,
    Fiscal Reintegration=0).

    The Phase 2B clean engine boundary does not represent the full 18-month
    source construction interval (2028-06-30 -> 2029-12-30) — it uses a 6-month
    proxy period (2029-07-01 to 2030-01-01). Therefore the construction-generated
    LCF is supplied at the operation boundary rather than computed through the
    period engine.

    origin_year=2029 is a MODEL_BOUNDARY_CONVENTION: the full workbook-observed
    construction-generated carryforward is assigned to the terminal year of the
    source construction/model period. No authoritative 2028-vs-2029 tax-year split
    has been extracted from the workbook. TUHO economics are unaffected by any
    possible expiry-year distinction because the loss is fully utilized before
    either possible expiry boundary (2033 or 2034).
    """
    amount_keur: float
    origin_label: str
    origin_year: int
    source_doc: str
    source_cells: str
    evidence_type: str
    workbook_sha: str


def build_construction_generated_carryforward_at_cod(baseline_id: str) -> tuple:
    """Return construction-generated LCF vintages at the operation boundary.

    DISTINCT from historical opening LCF (which is zero for TUHO).
    Source: construction-period SHL interest expensed through P&L with
    Fiscal Reintegration=0 -> tax loss generated during construction.

    The Phase 2B clean engine boundary uses a 6-month proxy construction period
    (2029-07-01 to 2030-01-01) rather than the full 18-month source construction
    interval (2028-06-30 -> 2029-12-30).  Mapping the 18-month IDC into the
    6-month proxy period is incorrect.  Instead the construction-generated LCF
    is supplied at the operation boundary via
    CONSTRUCTION_GENERATED_CARRYFORWARD_AT_OPERATION_BOUNDARY.

    origin_year=2029 is a MODEL_BOUNDARY_CONVENTION: the full workbook-observed
    construction-generated carryforward is assigned to the terminal year of the
    source construction/model period (2029-12-30).  No authoritative 2028-vs-2029
    tax-year split has been extracted.  TUHO economics are unaffected by the
    possible expiry-year distinction because the loss is fully utilized before
    either possible expiry boundary.

    Source: 20260330_TUHO_BP_2.xlsm (manual review,
    workbook_sha=UNAVAILABLE_NOT_CAPTURED).
    Evidence cells: DS G121-G126, P&L G27-G36.

    Raises
    ------
    RuntimeError
        If the registered construction fixture is missing or has invalid data
        (GOVERNANCE FAILURE — hard fail, never silently ignored).
    """
    if baseline_id == "tuho":
        import json
        import os
        fixture_path = "tests/fixtures/construction_parity/tuho_construction_snapshot.json"
        if not os.path.exists(fixture_path):
            raise RuntimeError(
                f"GOVERNANCE FAILURE: Registered TUHO construction fixture not found: "
                f"{fixture_path}"
            )
        with open(fixture_path) as f:
            snap = json.load(f)
        total_idc = snap.get("totals_keur", {}).get("total_shl_idc")
        if total_idc is None or total_idc <= 0:
            raise RuntimeError(
                f"GOVERNANCE FAILURE: TUHO construction snapshot missing or invalid "
                f"total_shl_idc: {total_idc}"
            )
        return (ConstructionGeneratedVintage(
            amount_keur=float(total_idc),
            origin_label="CONSTRUCTION_GENERATED",
            origin_year=2029,
            source_doc="20260330_TUHO_BP_2.xlsm",
            source_cells="DS G121-G126, P&L G27-G36",
            evidence_type="MANUAL_WORKBOOK_REVIEW",
            workbook_sha="UNAVAILABLE_NOT_CAPTURED",
        ),)
    return ()


