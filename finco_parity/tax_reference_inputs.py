"""finco_parity.tax_reference_inputs — Explicit per-baseline tax reference registry.

This module is the parity-layer source of truth for:
  * Per-baseline TaxPolicy (constructed from canonical project inputs).
  * Opening loss vintage positions.

It does NOT live inside financial_engine.  The financial_engine accepts an
explicit TaxPolicy and explicit opening vintages; project identity is resolved
HERE, in the parity adapter layer.

TUHO opening-loss: RESOLVED — ZERO (no pre-model vintages)
------------------------------------------------------------
Source: manual TUHO Excel workbook inspection (20260330_TUHO_BP_2.xlsm)

DS sheet (first modeled period):
  SHL Beginning    = 29,135 kEUR
  SHL PIK Interest =  3,569 kEUR
  SHL Ending       = 32,704 kEUR  (29,135 + 3,569 = 32,704 ✓)

P&L sheet (first modeled period):
  SHL Interest expense    = 3,569 kEUR
  Financial Earnings      = −3,569 kEUR
  EBT                     = −3,569 kEUR
  Fiscal Reintegration    = 0          (SHL interest currently deductible — EXCEL POLICY)
  Taxable Income          = −3,569 kEUR
  Losses N-1 (first period) = 0 / blank  (no pre-model carryforward)
  Losses N (first period)   = −3,569 kEUR (generated inside first period)
  Following period Losses N-1 = −3,569 kEUR (carried forward from first period)

Conclusions:
  1. SHL interest is simultaneously PIK'd into SHL liability AND expensed through P&L.
  2. No pre-model tax loss exists — opening LCF = ZERO.
  3. The 3,569 kEUR loss is generated by the model's first-period computation
     (SHL interest → P&L → taxable income). It is NOT an opening input.
  4. Prior factory value of 25,000 kEUR is unsupported as clean-engine source truth;
     retained unchanged in the legacy factory for compatibility and explicitly excluded
     from clean-engine tax source resolution.
  5. 3,569 kEUR must NOT be encoded as a historical/pre-construction opening vintage.

``build_opening_loss_vintages("tuho")`` returns an empty tuple ().

For baselines with no opening losses, an explicit reviewed-zero position is
recorded rather than relying on an absent tuple.
"""
